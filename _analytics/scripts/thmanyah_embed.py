"""Embed Thmanyah in the app's compiled CSS, the way the main site does (Thmanyah's approval;
README of this repo): a renamed subset inside the stylesheet, never a font file anyone can
download from the site.

Run on Mo's PC, from _analytics/, with the font package Mo downloaded from thmanyah.com:

  uv run --no-project --with "fonttools[woff]" python scripts/thmanyah_embed.py PATH/TO/Thmanyah-Font-Family.zip

It reads only the five cuts the app uses (brand/tokens.json: ar-small Sans Light, ar-body Sans
Regular, ar-heading Sans Bold, ar-title Serif Text Medium, ar-display Serif Display Bold), keeps
Arabic and Basic Latin and every OpenType layout feature (so «ر.س» still becomes the riyal sign),
renames the families (Rumh Sans, Rumh Text, Rumh Display) and writes src/styles/thmanyah.css.
No font file is written anywhere: the subsets exist only in memory and as data in that CSS.

The app follows Thmanyah's aesthetics guide: ligatures on; no swash letters (Stylistic
Alternates) and no slanted kashida or extended fatha (stylistic sets) in interface text, tables or
data. The guide reserves them for display headlines, never long text.
"""

from __future__ import annotations

import base64
import io
import sys
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

CUTS = [
    # (file in the package, family, weight)
    ("thmanyahsans/woff2/thmanyahsans-Light.woff2", "Rumh Sans", 300),
    ("thmanyahsans/woff2/thmanyahsans-Regular.woff2", "Rumh Sans", 400),
    ("thmanyahsans/woff2/thmanyahsans-Bold.woff2", "Rumh Sans", 700),
    ("thmanyahseriftext/woff2/thmanyahseriftext-Medium.woff2", "Rumh Text", 500),
    ("thmanyahserifdisplay/woff2/thmanyahserifdisplay-Bold.woff2", "Rumh Display", 700),
]
# Arabic, Arabic Supplement, presentation forms, Basic Latin, general punctuation, the riyal sign
UNICODES = (
    list(range(0x0020, 0x007F))
    + list(range(0x00A0, 0x00FF))
    + list(range(0x0600, 0x0700))
    + list(range(0x0750, 0x0780))
    + list(range(0xFB50, 0xFE00))
    + list(range(0xFE70, 0xFF00))
    + list(range(0x2000, 0x2070))
    + [0x20C1]
)
OUT = Path(__file__).resolve().parents[1] / "src" / "styles" / "thmanyah.css"


def read_cut(z: zipfile.ZipFile, tail: str) -> bytes:
    for n in z.namelist():
        if n.endswith(tail) and "__MACOSX" not in n:
            return z.read(n)
    raise SystemExit(f"{tail} isn't in the package")


def subset_cut(raw: bytes, family: str) -> bytes:
    font = TTFont(io.BytesIO(raw))
    opts = subset.Options()
    opts.layout_features = ["*"]  # liga keeps «ر.س» -> riyal; nothing else is switched on in CSS
    opts.flavor = "woff2"
    opts.name_IDs = []  # drop the original names; set our own below
    opts.notdef_outline = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=UNICODES)
    s.subset(font)
    name = font["name"]
    for rec_id, value in ((1, family), (2, "Regular"), (4, family), (6, family.replace(" ", ""))):
        name.setName(value, rec_id, 3, 1, 0x409)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main(pkg: str) -> None:
    with zipfile.ZipFile(pkg) as z:
        faces = []
        total = 0
        for tail, family, weight in CUTS:
            data = subset_cut(read_cut(z, tail), family)
            total += len(data)
            b64 = base64.b64encode(data).decode("ascii")
            faces.append(
                f'@font-face{{font-family:"{family}";src:url(data:font/woff2;base64,{b64}) '
                f'format("woff2");font-weight:{weight};font-style:normal;font-display:swap}}'
            )
    css = (
        "/* Generated by scripts/thmanyah_embed.py: Thmanyah, embedded as a compiled subset with no "
        "font files, used with Thmanyah's approval. Do not extract or reuse it. */\n"
        + "\n".join(faces)
        + '\n:root{--font-arabic:"Rumh Sans","IBM Plex Sans Arabic","Geeza Pro",sans-serif;'
        '--font-arabic-display:"Rumh Display","Rumh Sans","IBM Plex Sans Arabic",serif;'
        '--font-arabic-serif:"Rumh Text","Rumh Sans","IBM Plex Sans Arabic",serif}\n'
    )
    OUT.write_text(css, encoding="utf-8")
    print(f"{OUT.name}: {len(CUTS)} cuts, {total // 1024} KB of font data, {len(css) // 1024} KB CSS")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
